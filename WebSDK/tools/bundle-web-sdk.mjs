import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

export async function bundleWebSdk(repositoryRoot, version) {
  const contract = await readFile(resolve(repositoryRoot, 'packages/bridge-contract/src/index.js'), 'utf8');
  const sdk = await readFile(resolve(repositoryRoot, 'packages/web-sdk/src/index.js'), 'utf8');
  const localContract = contract.replace(/^export\s+/gm, '');
  const localSdk = sdk.replace(
    /import\s*\{[^}]+\}\s*from\s*['"]@memomind\/gm-plugin-bridge-contract['"];?\s*/,
    '',
  );
  return `// GM Web Plugin SDK ${version} · standalone ESM build\n// Generated by tools/bundle-web-sdk.mjs.\n\n${localContract}\n${localSdk}`;
}
