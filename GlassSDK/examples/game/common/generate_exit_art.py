"""Generate the original exit icon and analytic circular rings.

Run with Python + Pillow. Ring coverage comes from an annulus, not polygon
edges. Indexed images and LVGL 1.0 horizontal runs encode the same pixels.
Icon source: glassproject 09bd6ae5b, resources/images/common/icon_delete.png.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent


def ring_pixels(half):
    """48px outer diameter, 4px stroke, clockwise half from twelve o'clock."""
    pixels = []
    samples = 16
    for y in range(48):
        for x in range(48):
            covered = 0
            for sy in range(samples):
                dy = y + (sy + 0.5) / samples - 24
                for sx in range(samples):
                    dx = x + (sx + 0.5) / samples - 24
                    r2 = dx * dx + dy * dy
                    inside = 20 * 20 <= r2 <= 24 * 24
                    if half:
                        inside = (inside and dx >= 0) or (
                            dx * dx + (abs(dy) - 22) ** 2 <= 2 * 2)
                    covered += inside
            alpha = round(covered * 15 / (samples * samples)) * 17
            pixels.append((0, 240, 0, alpha))
    return pixels


def encode(name, width, height, pixels):
    palette = sorted(set(pixels))
    assert len(palette) <= 16
    payload = bytearray()
    for r, g, b, a in palette:
        payload.extend((b, g, r, a))
    payload.extend(bytes(64 - len(payload)))
    for y in range(height):
        for x in range(0, width, 2):
            payload.append((palette.index(pixels[y * width + x]) << 4) |
                           palette.index(pixels[y * width + x + 1]))
    runs = []
    for y in range(height):
        x = 0
        while x < width:
            start = x
            pixel = pixels[y * width + x]
            x += 1
            while x < width and pixels[y * width + x] == pixel:
                x += 1
            if pixel[3]:
                runs.append((start, y, x - start, pixel[1] & 0xF0, pixel[3]))
    text = f'static const firmware_exit_run_t {name}[] = {{\n'
    text += ''.join('    {%d, %d, %d, 0x%02X, %d},\n' % row for row in runs)
    text += f'}};\n_Alignas(4) static const uint8_t {name}_pixels[] = {{\n'
    for offset in range(0, len(payload), 16):
        text += '    ' + ', '.join(f'0x{v:02X}' for v in payload[offset:offset+16]) + ',\n'
    return text + '};\n'


def generate():
    image = Image.open(ROOT / 'icon_delete.png').convert('RGBA')
    assert image.size == (18, 18)
    text = '''/* Generated by generate_exit_art.py; do not edit by hand. */
#ifndef FIRMWARE_EXIT_ART_H
#define FIRMWARE_EXIT_ART_H
typedef struct { uint8_t x, y, width, green, alpha; } firmware_exit_run_t;
'''
    text += encode('firmware_exit_icon', 18, 18,
                   [image.getpixel((x, y)) for y in range(18) for x in range(18)])
    text += encode('firmware_exit_half', 48, 48, ring_pixels(True))
    text += encode('firmware_exit_full', 48, 48, ring_pixels(False))
    return text + '#endif\n'


if __name__ == '__main__':
    (ROOT / 'firmware_exit_art.h').write_text(generate(), encoding='utf-8')
